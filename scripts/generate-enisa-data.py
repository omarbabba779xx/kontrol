"""Regenerates src/lib/frameworks/data/enisa-data.ts from ENISA's NIS2 Technical Implementation Guidance mapping table.

  curl -L -o enisa.xlsx "https://www.enisa.europa.eu/sites/default/files/2025-09/ENISA_Technical_Implementation_Guidance_Mapping_table_version_1.2.xlsx"
  python scripts/generate-enisa-data.py enisa.xlsx > src/lib/frameworks/data/enisa-data.ts

The table correlates each point of the Annex to Commission Implementing Regulation (EU) 2024/2690 (the technical
requirements elaborating NIS2 Article 21(2)) with ISO/IEC 27001:2022 and NIST CSF 2.0. Its authors state it is not legally binding.
"""
import re, sys, json, warnings
warnings.filterwarnings("ignore")
import openpyxl

ws = openpyxl.load_workbook(sys.argv[1], read_only=True)["Mapping table"]


def iso_tokens(cell):
    text = str(cell or "").replace("Α", "A").replace("А", "A")  # Greek/Cyrillic capital A used in places
    text = re.sub(r"A\.\s*(\d)", r"A.\1", text)
    text = re.sub(r"(\d)\s+\.(\d)", r"\1.\2", text)
    out = []
    for token in re.split(r"[,\n;]+", text):
        token = token.strip()
        if not token or token == "-": continue
        annex = re.match(r"^A\.?\s*(\d)\.(\d{1,2})$", token)
        if annex:
            out.append(f"A{annex.group(1)}.{annex.group(2)}")
            continue
        clause = re.match(r"^(\d{1,2})\.(\d{1,2})(?:\.\d+)?$", token)
        if clause:
            major, minor = int(clause.group(1)), int(clause.group(2))
            # Bare numbers such as 5.28 can only be Annex A controls: clause 5 stops at 5.3.
            if major == 5 and minor > 3: out.append(f"A5.{minor}")
            elif 4 <= major <= 10: out.append(f"C{major}.{minor}")
    return sorted(set(out))


def csf_tokens(cell):
    return sorted({t for t in re.findall(r"[A-Z]{2}\.[A-Z]{2}-\d\d", str(cell or ""))})


points = []
for row in ws.iter_rows(min_row=3, values_only=True):
    point, title, iso, csf = (list(row) + [None] * 4)[:4]
    if point and re.match(r"^\d{1,2}\.\d{1,2}$", str(point).strip()):
        points.append((str(point).strip(), " ".join(str(title).split()), iso_tokens(iso), csf_tokens(csf)))

assert len(points) >= 45, len(points)
print("// Generated by scripts/generate-enisa-data.py from the ENISA NIS2 TIG mapping table v1.2. Do not edit by hand.")
print("/** [CIR 2024/2690 Annex point, title, ISO/IEC 27001:2022 references, NIST CSF 2.0 references] */")
print("export const ENISA_POINTS: Array<[string, string, string[], string[]]> = " + json.dumps(points, separators=(",", ":"), ensure_ascii=False).replace("],[", "],\n[") + ";")
