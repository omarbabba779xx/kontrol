"""Regenerates src/lib/frameworks/data/csf-data.ts from the official NIST CSF 2.0 Reference Tool export.

  curl -L -o csf.xlsx "https://csrc.nist.gov/extensions/nudp/services/json/csf/download?olirids=all"
  python scripts/generate-csf-data.py csf.xlsx > src/lib/frameworks/data/csf-data.ts

Only the 106 CSF 2.0 subcategories, their categories and the NIST-published informative references to
ISO/IEC 27001:2022, PCI DSS v4 sections and CIS Controls v8 safeguards are kept. NIST content is a U.S. Government work.
"""
import re, sys, json, warnings
warnings.filterwarnings("ignore")
import openpyxl

V2 = {"GV": ["OC", "RM", "RR", "PO", "OV", "SC"], "ID": ["AM", "RA", "IM"], "PR": ["AA", "AT", "DS", "PS", "IR"], "DE": ["CM", "AE"], "RS": ["MA", "AN", "CO", "MI"], "RC": ["RP", "CO"]}
FUNCTIONS = {"GV": "GOVERN", "ID": "IDENTIFY", "PR": "PROTECT", "DE": "DETECT", "RS": "RESPOND", "RC": "RECOVER"}
KEEP = {"ISO/IEC 27001": "iso", "PCI DSS": "pci", "CIS Controls v8.0": "cis"}
ws = openpyxl.load_workbook(sys.argv[1], read_only=True)["CSF 2.0"]
cats, subs = {}, []


def parse_refs(cell):
    """The reference cell is 'Framework: value' lines; continuation lines belong to the previous framework."""
    refs, current = {}, None
    for line in str(cell or "").split("\n"):
        m = re.match(r"^([A-Za-z][^:]*):\s*(.*)$", line)
        if m and not re.match(r"^(Mandatory Clause|Annex A Controls?|Control)$", m.group(1).strip()) and not re.match(r"^\d{4}$", m.group(1).strip()):
            current = m.group(1).strip()
            refs.setdefault(current, []).append(m.group(2))
        elif current and line.strip():
            refs[current].append(line)
    return refs


def iso_refs(items):
    out, state = {"clauses": set(), "annex": set()}, None
    for item in items:
        text = item.strip()
        if "Mandatory Clause" in text: state = "clauses"
        elif "Annex A" in text or "Control" in text: state = "annex"
        tail = text.split(":")[-1]
        for number in re.findall(r"\d+(?:\.\d+)+", tail):
            if state == "clauses": out["clauses"].add("C" + ".".join(number.split(".")[:2]))
            elif state == "annex": out["annex"].add("A" + number)
    return sorted(out["clauses"]) + sorted(out["annex"], key=lambda v: [int(p) for p in v[1:].split(".")])


def pci_refs(items):
    out = set()
    for item in items:
        for token in re.split(r"[,\s]+", item):
            m = re.match(r"^(\d{1,2})\.(\d{1,2})(?:\.|$)", token)
            if m: out.add(f"Req.{m.group(1)}.{m.group(2)}")
    return sorted(out, key=lambda v: [int(p) for p in v[4:].split(".")])


def cis_refs(items):
    out = set()
    for item in items:
        for token in re.split(r"[,\s]+", item):
            m = re.match(r"^(\d{1,2})\.(\d{1,2})$", token)
            if m and m.group(2) != "0": out.add(f"CIS.{m.group(1)}.{m.group(2)}")
    return sorted(out, key=lambda v: [int(p) for p in v[4:].split(".")])


for row in ws.iter_rows(values_only=True):
    _, cat, sub, ex, ref = (list(row) + [None] * 5)[:5]
    if cat:
        m = re.match(r"^(.+?) \(([A-Z]{2}\.[A-Z]{2})\):", str(cat))
        if m and m.group(2).split(".")[1] in V2.get(m.group(2).split(".")[0], []): cats[m.group(2)] = " ".join(m.group(1).split())
    # CSF 2.0 rows carry implementation examples; the legacy v1.1 rows appended to the sheet do not.
    if sub and ex and re.match(r"^[A-Z]{2}\.[A-Z]{2}-\d\d", str(sub).strip()):
        sid, text = str(sub).split(":", 1)
        sid = sid.strip()
        fn, ct = sid.split("-")[0].split(".")
        if ct not in V2.get(fn, []): continue
        refs = parse_refs(ref)
        subs.append((sid, " ".join(text.split()), iso_refs(refs.get("ISO/IEC 27001", [])), pci_refs(refs.get("PCI DSS", [])), cis_refs(refs.get("CIS Controls v8.0", []))))

assert len(subs) == 106, len(subs)
print("// Generated by scripts/generate-csf-data.py from the NIST CSF 2.0 Reference Tool export. Do not edit by hand.")
print("export const CSF_FUNCTIONS: Record<string, string> = " + json.dumps(FUNCTIONS) + ";")
print("export const CSF_CATEGORIES: Array<{ id: string; title: string }> = " + json.dumps([{"id": k, "title": v} for k, v in cats.items()], indent=1) + ";")
print("/** [id, title, ISO/IEC 27001:2022, PCI DSS 4 sections, CIS Controls v8 safeguards: informative references published by NIST] */")
print("export const CSF_SUBCATEGORIES: Array<[string, string, string[], string[], string[]]> = " + json.dumps(subs, separators=(",", ":")).replace("],[", "],\n[") + ";")
